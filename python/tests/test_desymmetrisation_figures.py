"""Tests for the manuscript's figures and the numbers they carry.

The figures are generated by `scripts/generate_desymmetrisation_figures.py`, which
computes every plotted number at draw time. These tests do two things: they run the
generator (so a broken figure fails here rather than in a reader's browser), and they
re-derive the numbers the manuscript quotes, so that a figure and its caption cannot
drift apart.

The manuscript's tables are the literals below, transcribed from
`docs/desymmetrisation_paper.md` (Appendix B and Appendix C). If a measurement moves,
this module fails and the manuscript has to move with it.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import numpy as np
import pytest

from riemann_framework.desymmetrisation import (
    calibration_table,
    default_sector_count_model,
    superposition_spectrum,
)

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
OUTPUT_DIR = PROJECT_ROOT / "output"
GENERATOR = PROJECT_ROOT / "scripts" / "generate_desymmetrisation_figures.py"

FIGURE_FILES = (
    "desymmetrisation_warning.png",
    "desymmetrisation_coverage.png",
    "desymmetrisation_flow.png",
)

#: Appendix B of the manuscript: true sector count -> measured coverage.
MANUSCRIPT_COVERAGE = {
    1: 1.00,
    2: 0.93,
    3: 0.87,
    4: 0.98,
    5: 1.00,
    6: 0.97,
    None: 0.78,
}


def test_the_generator_writes_every_manuscript_figure():
    """A figure that cannot be regenerated is not evidence; run the generator."""
    result = subprocess.run(
        [sys.executable, str(GENERATOR)],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
        timeout=1800,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    for name in FIGURE_FILES:
        path = OUTPUT_DIR / name
        assert path.exists(), f"the generator did not write {name}"
        assert path.stat().st_size > 20_000, f"{name} is suspiciously small"
    assert "coverage" in result.stdout


def test_the_coverage_table_matches_the_manuscript():
    """Appendix B, re-derived: each row within binomial noise of the published value."""
    rows = default_sector_count_model().coverage(draws=60)
    by_truth = {row.truth: row for row in rows}
    assert set(by_truth) == set(MANUSCRIPT_COVERAGE)
    for truth, published in MANUSCRIPT_COVERAGE.items():
        measured = by_truth[truth].coverage
        assert measured == pytest.approx(published, abs=0.08), (
            f"truth {truth}: manuscript says {published}, measured {measured}"
        )
    assert by_truth[1].coverage == 1.0
    assert by_truth[1].posterior_probability == pytest.approx(0.98, abs=0.05)


def test_the_two_sector_gap_is_smaller_than_the_scatter():
    """Appendix A's quantitative claim: the class is erased, not merely noisy."""
    rows = calibration_table((1, 2), dimension=60, seeds=60)
    one = {row.matrix_class: row for row in rows if row.n_sectors == 1}
    two = {row.matrix_class: row for row in rows if row.n_sectors == 2}
    gap = abs(two["goe"].mean_r - two["gue"].mean_r)
    assert gap < min(two["goe"].std_r, two["gue"].std_r)
    assert one["goe"].mean_r > two["goe"].mean_r
    assert one["gue"].mean_r > two["gue"].mean_r


def test_the_false_positive_rate_is_the_manuscripts():
    """Appendix C: 4 of 40 pure single-sector GOE spectra fall below the floor."""
    from riemann_framework.desymmetrisation import SINGLE_SECTOR_FLOOR
    from riemann_framework.statistics import mean_r_ratio

    flagged = 0
    for seed in range(40):
        values = superposition_spectrum(1, 60, "goe", seed)
        if float(mean_r_ratio(values, unfold=False)) < SINGLE_SECTOR_FLOOR:
            flagged += 1
    assert flagged == 4


def test_the_flow_figure_uses_measured_panels():
    """The two panels of Fig. 4 are the two measured behaviours, not a drawn curve."""
    from riemann_framework.dimension_shift_chaos import (
        build_dimension_shift_hamiltonian,
        sector_swap,
    )
    from riemann_framework.dynamical_desymmetrisation import (
        commutator_norm,
        dynamical_desymmetrise,
    )

    dimension = 4
    hamiltonian = build_dimension_shift_hamiltonian(dimension, 1.0, "gue", seed=0)
    involution = sector_swap(dimension)
    size = 2 * dimension
    rng = np.random.default_rng(0)

    def sector_vector(sign: int) -> np.ndarray:
        projector = (np.eye(size) + sign * involution) / 2.0
        basis, _, _ = np.linalg.svd(projector)
        coefficients = rng.standard_normal(2) + 1j * rng.standard_normal(2)
        vector = basis[:, :2] @ coefficients
        return vector / np.linalg.norm(vector)

    commuting = np.zeros((size, size), dtype=complex)
    for sign in (+1, -1):
        vector = sector_vector(sign)
        commuting += 0.5 * np.outer(vector, vector.conj())

    def sector_state(sign: int, index: int) -> np.ndarray:
        local = (np.eye(size) + sign * involution) / 2.0
        _, basis = np.linalg.eigh(
            local @ hamiltonian @ local + 1e6 * (np.eye(size) - local)
        )
        return basis[:, index]

    vector = (sector_state(+1, 0) + sector_state(-1, 0)) / np.sqrt(2.0)
    cross = np.outer(vector, vector.conj())

    preserved = dynamical_desymmetrise(
        hamiltonian, involution, commuting, beta=15.0, steps=3000
    )
    selected = dynamical_desymmetrise(
        hamiltonian, involution, cross, beta=15.0, steps=3000
    )

    assert commutator_norm(commuting, involution) < 1e-8
    assert commutator_norm(commuting, hamiltonian) > 0.5
    assert np.allclose(preserved.sector_populations[0], [0.5, 0.5], atol=1e-9)
    assert np.allclose(preserved.sector_populations[-1], [0.5, 0.5], atol=1e-6)
    assert preserved.spectrum_drift < 1e-9

    assert selected.coherences[0] > 1.0
    assert selected.coherences[-1] < 0.01
    assert selected.sector_populations[-1].max() > 0.99
    assert selected.spectrum_drift < 1e-9